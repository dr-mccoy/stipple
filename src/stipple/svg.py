from __future__ import annotations

import base64
import hashlib
import json
import re
from functools import cache
from importlib.resources import files
from xml.etree import ElementTree as ET

from .model import Box, DiagramError, Drawing, Point
from .style import CLASSIC
from .text import measure

INK = CLASSIC.ink
PAPER = CLASSIC.paper


def number(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".") or "0"


def element(parent: ET.Element, tag: str, **attributes) -> ET.Element:
    return ET.SubElement(
        parent,
        tag,
        {
            name.replace("_", "-"): (
                number(value) if isinstance(value, (int, float)) else str(value)
            )
            for name, value in attributes.items()
        },
    )


def rectangle(parent: ET.Element, box: Box, **attributes) -> ET.Element:
    return element(
        parent, "rect", x=box.x, y=box.y, width=box.width, height=box.height, **attributes
    )


def path(parent: ET.Element, points: tuple[Point, ...], **attributes) -> ET.Element:
    d = "M " + " L ".join(f"{number(p.x)} {number(p.y)}" for p in points)
    return element(parent, "path", d=d, fill="none", **attributes)


def text(parent: ET.Element, label: str, box: Box, size: float, *, left: bool = False):
    measured = measure(label, size)
    x = box.x if left else box.center.x
    y = box.y + (box.height - measured.height) / 2 + measured.ascent
    node = element(
        parent,
        "text",
        x=x,
        y=y,
        fill=INK,
        stroke="none",
        text_anchor="start" if left else "middle",
        font_size=size,
    )
    node.set("xml:space", "preserve")
    for i, line in enumerate(measured.lines):
        element(node, "tspan", x=x, y=y + i * measured.line_height).text = line


@cache
def embedded_font() -> str:
    font = files("stipple").joinpath("assets/CourierPrime-Regular.ttf").read_bytes()
    return base64.b64encode(font).decode("ascii")


def render_svg(drawing: Drawing, *, id_prefix: str | None = None) -> str:
    diagram, bounds = drawing.diagram, drawing.bounds
    if id_prefix is None:
        # Diagnostic locations do not affect the identity of the drawing.
        content = json.dumps(
            {
                "title": diagram.title,
                "description": diagram.description,
                "font_size": diagram.font_size,
                "nodes": [
                    (n.id, n.kind, n.label, n.shadow, n.orientation, vars(drawing.boxes[n.id]))
                    for n in diagram.nodes.values()
                ],
                "edges": [
                    (
                        e.edge.start.node,
                        e.edge.end.node,
                        e.edge.arrow,
                        e.edge.label,
                        [(p.x, p.y) for p in e.points],
                        vars(e.label_box) if e.label_box else None,
                    )
                    for e in drawing.edges
                ],
                "style": vars(CLASSIC),
            },
            sort_keys=True,
        )
        id_prefix = "stipple-" + hashlib.sha256(content.encode()).hexdigest()[:12]
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9-]*", id_prefix):
        raise DiagramError(
            "SVG id prefix must be an identifier starting with a letter or underscore"
        )
    root = ET.Element(
        "svg",
        {
            "xmlns": "http://www.w3.org/2000/svg",
            "viewBox": " ".join(map(number, (bounds.x, bounds.y, bounds.width, bounds.height))),
            "width": number(bounds.width),
            "height": number(bounds.height),
            "role": "img",
            "aria-labelledby": f"{id_prefix}-title {id_prefix}-desc",
        },
    )
    element(root, "title", id=f"{id_prefix}-title").text = diagram.title
    description = diagram.description or "; ".join(
        node.label.replace("\n", ", ") for node in diagram.nodes.values() if node.label
    )
    element(root, "desc", id=f"{id_prefix}-desc").text = description
    element(root, "metadata").text = (
        "Generated by Stipple. Embedded Courier Prime font license:\n"
        + "\n".join(
            line.rstrip()
            for line in files("stipple").joinpath("assets/OFL.txt").read_text("utf-8").splitlines()
        )
    )
    defs = element(root, "defs")
    family = f"{id_prefix}-font"
    element(defs, "style").text = (
        f"@font-face{{font-family:'{family}';src:url(data:font/ttf;base64,{embedded_font()}) "
        "format('truetype');font-style:normal;font-weight:400;}"
    )
    pattern = element(
        defs,
        "pattern",
        id=f"{id_prefix}-dots",
        width=CLASSIC.dot_pitch,
        height=CLASSIC.dot_pitch,
        patternUnits="userSpaceOnUse",
    )
    for fraction in (0.25, 0.75):
        element(
            pattern,
            "circle",
            cx=CLASSIC.dot_pitch * fraction,
            cy=CLASSIC.dot_pitch * fraction,
            r=CLASSIC.dot_radius,
            fill=INK,
        )
    marker = element(
        defs,
        "marker",
        id=f"{id_prefix}-arrow",
        viewBox="0 0 8 8",
        refX=8,
        refY=4,
        markerWidth=7,
        markerHeight=7,
        orient="auto",
        markerUnits="userSpaceOnUse",
    )
    element(marker, "path", d="M 0 0 L 8 4 L 0 8 Z", fill=INK)
    rectangle(root, bounds, fill=PAPER)
    group = element(
        root,
        "g",
        font_family=family,
        font_weight="400",
        font_style="normal",
        font_kerning="none",
        font_variant_ligatures="none",
        stroke=INK,
        stroke_width=CLASSIC.stroke,
        stroke_linejoin="miter",
    )
    for name, node in diagram.nodes.items():
        if node.shadow:
            box = drawing.boxes[name]
            rectangle(
                group,
                Box(box.x + CLASSIC.shadow_x, box.y + CLASSIC.shadow_y, box.width, box.height),
                fill=f"url(#{id_prefix}-dots)",
                stroke="none",
            )
    for routed in drawing.edges:
        edge_group = element(
            group, "g", **{"data-from": routed.edge.start.node, "data-to": routed.edge.end.node}
        )
        path(edge_group, routed.points, stroke=PAPER, stroke_width=4)
        attrs = {"marker_end": f"url(#{id_prefix}-arrow)"} if routed.edge.arrow else {}
        path(edge_group, routed.points, **attrs)
    for name, node in diagram.nodes.items():
        box = drawing.boxes[name]
        node_group = element(group, "g", id=f"{id_prefix}-node-{name}")
        if node.kind in {"box", "text"}:
            if node.kind == "box":
                rectangle(node_group, box, fill=PAPER)
            text(node_group, node.label, box, diagram.font_size)
        elif node.kind == "junction":
            element(
                node_group,
                "circle",
                cx=box.center.x,
                cy=box.center.y,
                r=2.5,
                fill=INK,
                stroke="none",
            )
        else:
            component(node_group, node.kind, node.label, box, diagram.font_size, node.orientation)
    for routed in drawing.edges:
        if routed.label_box:
            rectangle(group, routed.label_box, fill=PAPER, stroke="none")
            text(group, routed.edge.label, routed.label_box, diagram.font_size)
    return ET.tostring(root, encoding="unicode", short_empty_elements=True) + "\n"


def component(parent: ET.Element, kind: str, label: str, box: Box, size: float, orientation: str):
    if orientation == "right":
        y, center = box.bottom - 10, box.center.x
        if kind == "resistor":
            path(parent, (Point(box.x, y), Point(center - 20, y)))
            rectangle(parent, Box(center - 20, y - 7, 40, 14), fill=PAPER)
            path(parent, (Point(center + 20, y), Point(box.right, y)))
        else:
            for sign, terminal_x in ((-1, box.x), (1, box.right)):
                x = center + sign * 4
                path(parent, (Point(terminal_x, y), Point(x, y)))
                path(parent, (Point(x, y - 9), Point(x, y + 9)), stroke_width=2)
        text(parent, label, Box(box.x, box.y, box.width, box.height - 30), size)
    else:
        x, center = box.x + 9, box.center.y
        if kind == "resistor":
            path(parent, (Point(x, box.y), Point(x, center - 18)))
            rectangle(parent, Box(x - 6, center - 18, 12, 36), fill=PAPER)
            path(parent, (Point(x, center + 18), Point(x, box.bottom)))
        else:
            for sign, terminal_y in ((-1, box.y), (1, box.bottom)):
                y = center + sign * 4
                path(parent, (Point(x, terminal_y), Point(x, y)))
                path(parent, (Point(x - 8, y), Point(x + 8, y)), stroke_width=2)
        text(parent, label, Box(box.x + 26, box.y, box.width - 26, box.height), size, left=True)
